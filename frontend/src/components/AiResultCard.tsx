import type { ReactNode } from 'react';
import { Cpu, Sparkles } from 'lucide-react';
import { formatTime } from '../lib/format';
import type { AiResult } from '../lib/types';

type AiSourceInfo = Pick<AiResult<unknown>, 'source' | 'provider' | 'model'>;

/** Source label shown on every AI output: real LLM vs the deterministic fallback engine. */
export function AiSourceBadge({ result }: { result: AiSourceInfo }) {
  if (result.source === 'LLM') {
    const label = ['LLM', result.provider, result.model].filter(Boolean).join(' · ');
    return (
      <span className="badge llm" title="Generated by a large language model">
        <Sparkles size={10} /> {label}
      </span>
    );
  }
  return (
    <span className="badge fallback" title="Produced by rules and statistics, not a language model">
      <Cpu size={10} /> Deterministic fallback — not AI-generated
    </span>
  );
}

/** Compact one-word source label for dense lists ("LLM" / "Fallback"), with the full label as tooltip. */
export function AiSourceTag({ source }: { source: AiResult<unknown>['source'] }) {
  const llm = source === 'LLM';
  return (
    <span className={`badge ${llm ? 'llm' : 'fallback'}`} title={llm ? 'Generated by a large language model' : 'Deterministic fallback — not AI-generated'}>
      {llm ? <Sparkles size={10} /> : <Cpu size={10} />} {llm ? 'LLM' : 'Fallback'}
    </span>
  );
}

interface AiResultCardProps {
  result: AiResult<unknown>;
  title?: ReactNode;
  children: ReactNode;
  actions?: ReactNode;
  /** Extra content beside the title (e.g. a "87% Match" badge). */
  badge?: ReactNode;
  /** Hides the generated-at / latency suffix of the notice line (the notice itself always shows). */
  compact?: boolean;
  className?: string;
}

/**
 * Wrapper for every AI output: the LLM / deterministic-fallback source badge and the API notice are always shown.
 * Rendered as an `article` named after `title` (string titles) so tests and screen readers can find it.
 */
export function AiResultCard({ result, title, children, actions, badge, compact = false, className = '' }: AiResultCardProps) {
  const fallback = result.source !== 'LLM';
  return (
    <article className={`ai-result ${fallback ? 'fallback' : ''} ${className}`.trim()} aria-label={typeof title === 'string' ? title : 'SA AI result'}>
      <div className="mb-2 flex flex-wrap items-center justify-between gap-2">
        {title || badge ? (
          <div className="flex min-w-0 flex-wrap items-center gap-2">
            {title && <h4>{title}</h4>}
            {badge}
          </div>
        ) : (
          <span />
        )}
        <AiSourceBadge result={result} />
      </div>
      <div>{children}</div>
      {actions && <div className="mt-3 flex flex-wrap gap-2">{actions}</div>}
      <p className="ai-notice">
        {result.notice}
        {fallback && result.fallbackReason ? ` (${result.fallbackReason})` : ''}
        {!compact && (
          <span className="muted-text">
            {' '}
            · {formatTime(result.generatedAt)} · {result.latencyMs} ms
          </span>
        )}
      </p>
    </article>
  );
}
