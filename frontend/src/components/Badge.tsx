import type { ReactNode } from 'react';
import { badgeClass, titleCase } from '../lib/format';
import { ARTICLE_STATUS_LABELS, PRIORITY_LABELS, REQUEST_STATUS_LABELS, ROLE_LABELS, STATUS_LABELS, type Tone } from '../lib/constants';
import type { Priority, Role } from '../lib/types';

interface BadgeProps {
  /** Enum/status value; drives both the colour class and (by default) the Title Case label. */
  value: string | null | undefined;
  label?: ReactNode;
  className?: string;
  title?: string;
  /** Explicit colour instead of the value-derived one. */
  tone?: Tone;
}

export function Badge({ value, label, className = '', title, tone }: BadgeProps) {
  if (!value && !label) return null;
  return (
    <span className={`badge ${tone ? `tone-${tone}` : badgeClass(value)} ${className}`.trim()} title={title}>
      {label ?? titleCase(value)}
    </span>
  );
}

const STATUS_TEXT: Record<string, string> = { ...REQUEST_STATUS_LABELS, ...ARTICLE_STATUS_LABELS, ...STATUS_LABELS };

/**
 * Status pill for incidents (New, Assigned, In Progress, Pending, Resolved, Closed, Reopened) and any other
 * status enum (requests, approvals, executions…). Unknown values — e.g. Release 1 history — are title-cased.
 */
export function StatusBadge({ status, className }: { status: string | null | undefined; className?: string }) {
  if (!status) return null;
  return <Badge value={status} label={STATUS_TEXT[status] ?? titleCase(status)} className={className} />;
}

/** Priority pill in the spec colours (Critical red, High amber, Medium champagne, Low neutral). */
export function PriorityBadge({ priority, className = '' }: { priority: Priority | null | undefined; className?: string }) {
  if (!priority) return null;
  return <Badge value={priority} label={PRIORITY_LABELS[priority] ?? titleCase(priority)} className={`priority ${className}`.trim()} />;
}

export function RoleBadge({ role }: { role: Role }) {
  return <Badge value={role} label={ROLE_LABELS[role] ?? titleCase(role)} className="role" />;
}

/** Marks seeded demonstration records so they are never mistaken for live data. */
export function DemoBadge({ demo }: { demo: boolean | null | undefined }) {
  if (!demo) return null;
  return (
    <span className="badge demo" title="Seeded demonstration record">
      DEMO
    </span>
  );
}

/**
 * Marks sample data generated by simulation mode (RELEASE4_SPEC §0.2): every record with `simulated: true` shows it,
 * so simulated figures are never mistaken for live data.
 */
export function SimulatedBadge({ simulated, className = '' }: { simulated: boolean | null | undefined; className?: string }) {
  if (!simulated) return null;
  return (
    <span className={`badge simulated ${className}`.trim()} title="Sample data generated by simulation mode — not a real event">
      SIMULATION
    </span>
  );
}

export function BooleanBadge({ value, on = 'Active', off = 'Inactive' }: { value: boolean; on?: string; off?: string }) {
  return <Badge value={value ? 'active' : 'inactive'} label={value ? on : off} />;
}
