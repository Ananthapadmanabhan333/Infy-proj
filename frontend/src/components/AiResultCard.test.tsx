import { render, screen } from '@testing-library/react';
import { describe, expect, it } from 'vitest';
import type { AiResult } from '../lib/types';
import { AiResultCard, AiSourceBadge, AiSourceTag } from './AiResultCard';

const base: AiResult<unknown> = {
  source: 'FALLBACK',
  provider: 'fallback',
  model: null,
  generatedAt: '2026-11-03T10:00:00Z',
  latencyMs: 15,
  notice: 'Computed by the deterministic engine.',
  fallbackReason: 'No LLM provider configured',
  data: null,
};

describe('AiResultCard', () => {
  it('labels deterministic output honestly and always shows the notice and fallback reason', () => {
    render(
      <AiResultCard result={base} title="Recommended knowledge">
        <p>Body</p>
      </AiResultCard>,
    );
    const card = screen.getByRole('article', { name: 'Recommended knowledge' });
    expect(card).toHaveClass('fallback');
    expect(card).toHaveTextContent('Deterministic fallback — not AI-generated');
    expect(card).toHaveTextContent('Computed by the deterministic engine. (No LLM provider configured)');
    expect(card).toHaveTextContent('15 ms');
  });

  it('names the LLM provider and model, and supports a badge and compact notice', () => {
    render(
      <AiResultCard result={{ ...base, source: 'LLM', provider: 'anthropic', model: 'claude-test', fallbackReason: null }} title="SA AI Recommendation" badge={<span>87% Match</span>} compact>
        <p>Body</p>
      </AiResultCard>,
    );
    const card = screen.getByRole('article', { name: 'SA AI Recommendation' });
    expect(card).not.toHaveClass('fallback');
    expect(card).toHaveTextContent('LLM · anthropic · claude-test');
    expect(card).toHaveTextContent('87% Match');
    expect(card).not.toHaveTextContent('15 ms');
  });

  it('exposes compact source badges for lists', () => {
    render(
      <>
        <AiSourceBadge result={base} />
        <AiSourceTag source="LLM" />
        <AiSourceTag source="FALLBACK" />
      </>,
    );
    expect(screen.getByText('Deterministic fallback — not AI-generated')).toBeInTheDocument();
    expect(screen.getByTitle('Generated by a large language model')).toHaveTextContent('LLM');
    expect(screen.getByTitle('Deterministic fallback — not AI-generated')).toHaveTextContent('Fallback');
  });
});
