import { screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { Route, Routes, useLocation, useParams } from 'react-router-dom';
import { beforeAll, describe, expect, it } from 'vitest';
import type { AiResult, IncidentSummary, Role } from '../lib/types';
import { json, mockApi, requests, type MockReply } from '../test/mockApi';
import { makeAuth, makeUser, renderWithProviders } from '../test/utils';
import AiPage from './AiPage';

function aiResult<T>(data: T, source: 'LLM' | 'FALLBACK' = 'FALLBACK'): AiResult<T> {
  return {
    source,
    provider: source === 'LLM' ? 'anthropic' : 'fallback',
    model: source === 'LLM' ? 'claude-test' : null,
    generatedAt: '2026-11-03T10:00:00Z',
    latencyMs: 12,
    notice: source === 'LLM' ? 'Generated by a language model.' : 'Computed by the deterministic engine.',
    fallbackReason: source === 'LLM' ? null : 'No LLM provider configured',
    data,
  };
}

const incident = {
  id: 7846,
  number: 'INC-7846',
  title: 'Payroll application not accessible',
  priority: 'CRITICAL',
  status: 'IN_PROGRESS',
} as IncidentSummary;

const insights = aiResult({
  insights: [
    { title: 'VPN latency reports are recurring', detail: '6 similar incidents.', severity: 'INFO', metric: '6', confidence: 'MEDIUM' },
    { title: 'Payroll incidents are 78% higher between 10 AM – 12 PM', detail: '41% of payroll incidents.', severity: 'WARNING', metric: '+78%', confidence: 'HIGH' },
  ],
  hourly: [
    { hour: 9, count: 4 },
    { hour: 10, count: 30 },
    { hour: 11, count: 12 },
  ],
});

function baseRoutes(extra: Record<string, MockReply | ((config: never) => MockReply)> = {}) {
  mockApi({
    'GET /ai/status': json({ provider: 'fallback', model: null, llmConfigured: false, llmEnabled: false, fallbackAvailable: true, lastError: null }),
    'POST /ai/insights': json(insights),
    'GET /ai/interactions': json([
      { id: 2, feature: 'ROOT_CAUSE', subject: 'INC-7846', source: 'FALLBACK', createdAt: '2026-11-03T09:50:00Z' },
      { id: 1, feature: 'ASK', subject: 'Incident trend – last 30 days', source: 'LLM', createdAt: '2026-11-02T09:00:00Z' },
    ]),
    'GET /incidents': json({ content: [incident], page: 0, size: 5, totalElements: 1, totalPages: 1 }),
    ...extra,
  });
}

function IncidentRoute() {
  const { id } = useParams();
  return <p>Incident page {id}</p>;
}

function BuilderRoute() {
  const location = useLocation();
  const state = location.state as { suggestion?: { name: string; triggerEvent: string } } | null;
  return (
    <p>
      Builder with {state?.suggestion?.name} ({state?.suggestion?.triggerEvent})
    </p>
  );
}

function renderPage(role: Role = 'SYSTEM_ADMIN', route = '/sa-ai') {
  return renderWithProviders(
    <Routes>
      <Route path="/sa-ai" element={<AiPage />} />
      <Route path="/incidents/:id" element={<IncidentRoute />} />
      <Route path="/automation/new" element={<BuilderRoute />} />
    </Routes>,
    { route, auth: makeAuth(makeUser(role)) },
  );
}

beforeAll(() => {
  // Recharts' ResponsiveContainer (Predict chart) needs ResizeObserver, which jsdom lacks.
  globalThis.ResizeObserver ??= class {
    observe() {}
    unobserve() {}
    disconnect() {}
  } as unknown as typeof ResizeObserver;
});

describe('AiPage (SA AI)', () => {
  it('shows the title, Beta badge, honest fallback notice and the four capability tiles', async () => {
    baseRoutes();
    renderPage();
    expect(screen.getByRole('heading', { level: 1 })).toHaveTextContent('SA AI');
    expect(screen.getByText('Beta')).toBeInTheDocument();
    expect(screen.getByText('Your IT operations co-pilot')).toBeInTheDocument();
    const status = await screen.findByRole('note', { name: 'SA AI engine status' });
    expect(status).toHaveTextContent('Fallback engine active');
    expect(status).toHaveTextContent('no LLM provider is configured');
    expect(status).toHaveTextContent('not AI-generated');
    const tiles = screen.getByRole('group', { name: 'SA AI capabilities' });
    expect(within(tiles).getAllByRole('button').map((button) => button.getAttribute('aria-label'))).toEqual([
      'Analyze — Investigate incidents',
      'Predict — Forecast issues',
      'Recommend — Resolution steps',
      'Automate — Create workflows',
    ]);
  });

  it('hides the tiles a role cannot use', async () => {
    baseRoutes();
    renderPage('SUPPORT_AGENT');
    let tiles = screen.getByRole('group', { name: 'SA AI capabilities' });
    expect(within(tiles).queryByRole('button', { name: /Automate/ })).not.toBeInTheDocument();
    expect(within(tiles).getByRole('button', { name: /Recommend/ })).toBeInTheDocument();
  });

  it('auditors see Analyze and Predict only', () => {
    baseRoutes();
    renderPage('AUDITOR');
    const tiles = screen.getByRole('group', { name: 'SA AI capabilities' });
    expect(within(tiles).getAllByRole('button')).toHaveLength(2);
    expect(within(tiles).queryByRole('button', { name: /Recommend/ })).not.toBeInTheDocument();
  });

  it('asks a question and renders the grounded answer with data, basis and source label', async () => {
    baseRoutes({
      'POST /ai/ask': json(
        aiResult({ answer: 'Payroll has the most open incidents.', data: [{ label: 'Payroll', value: 12 }, { label: 'Network', value: 7 }], basis: 'Active incidents grouped by service.' }),
      ),
    });
    renderPage();
    const user = userEvent.setup();
    await user.type(screen.getByRole('textbox', { name: 'Ask SA AI anything' }), 'Which services have the most open incidents?');
    await user.click(screen.getByRole('button', { name: 'Send question' }));

    const thread = await screen.findByLabelText('Conversation');
    expect(within(thread).getByText('Which services have the most open incidents?')).toBeInTheDocument();
    const answer = await within(thread).findByRole('article', { name: 'SA AI' });
    expect(answer).toHaveTextContent('Payroll has the most open incidents.');
    expect(within(answer).getByText('Deterministic fallback — not AI-generated')).toBeInTheDocument();
    expect(within(answer).getByRole('table', { name: 'Answer data' })).toHaveTextContent('Payroll');
    expect(answer).toHaveTextContent('Based on: Active incidents grouped by service.');
    expect(requests.find((r) => r.method === 'POST' && r.url === '/ai/ask')?.body).toEqual({ question: 'Which services have the most open incidents?' });
    expect(screen.getByRole('textbox', { name: 'Ask SA AI anything' })).toHaveValue('');
  });

  it('shows a rate-limit message when the AI call is throttled', async () => {
    baseRoutes({ 'POST /ai/ask': { status: 429, data: { status: 429, error: 'Too Many Requests', message: 'Too many requests', path: '/api/ai/ask', timestamp: '' } } });
    renderPage();
    const user = userEvent.setup();
    await user.type(screen.getByRole('textbox', { name: 'Ask SA AI anything' }), 'Hello there');
    await user.click(screen.getByRole('button', { name: 'Send question' }));
    expect(await screen.findByText(/rate limit reached/)).toBeInTheDocument();
  });

  it('shows the most significant insight of the day with its confidence and hourly sparkline', async () => {
    baseRoutes();
    renderPage();
    const card = await screen.findByRole('region', { name: /Insight of the Day/ });
    expect(await within(card).findByText(/Payroll incidents are 78% higher/)).toBeInTheDocument();
    expect(within(card).getByText('High confidence')).toBeInTheDocument();
    expect(within(card).getByRole('img', { name: /Incidents created by hour of day.*Peak 10:00–11:00/ })).toBeInTheDocument();
    expect(within(card).getByText('Deterministic fallback — not AI-generated')).toBeInTheDocument();
  });

  it('lists recent analyses and opens the incident behind an incident subject', async () => {
    baseRoutes();
    renderPage();
    const recent = await screen.findByRole('region', { name: 'Recent Analyses' });
    const row = await within(recent).findByRole('button', { name: 'Root cause – INC-7846: open incident' });
    // Non-incident subjects are not clickable.
    expect(within(recent).getByText('Question – Incident trend – last 30 days').closest('button')).toBeNull();
    await userEvent.setup().click(row);
    expect(await screen.findByText('Incident page 7846')).toBeInTheDocument();
  });

  it('Predict is labelled as a statistical model, not AI', async () => {
    baseRoutes({
      'GET /analytics/forecast': json({
        history: [
          { date: '2026-11-01', count: 10 },
          { date: '2026-11-02', count: 12 },
        ],
        forecast: [{ date: '2026-11-03', predicted: 13, lower: 10, upper: 16 }],
        method: 'LINEAR_REGRESSION',
        slope: 1,
        rSquared: 0.7,
        byService: [{ serviceName: 'Payroll', last7Days: 6, next7Days: 8 }],
      }),
    });
    renderPage('SYSTEM_ADMIN', '/sa-ai?tool=predict');
    expect(await screen.findByText('Statistical model — not AI')).toBeInTheDocument();
    expect(screen.getByText(/Linear Regression/)).toBeInTheDocument();
    expect(screen.getByRole('table', { name: 'Forecast by service' })).toHaveTextContent('Payroll');
  });

  it('Analyze runs the summary and root-cause analysis for the picked incident', async () => {
    baseRoutes({
      'POST /ai/incidents/7846/summarize': json(aiResult({ summary: 'Users cannot reach payroll.', keyFacts: ['320 users'], nextSteps: ['Check DB pool'] })),
      'POST /ai/incidents/7846/root-cause': json(
        aiResult({ hypotheses: [{ cause: 'Connection pool exhaustion', likelihood: 'HIGH', evidence: ['Pool at 97%'], suggestedChecks: ['Check pool'] }] }),
      ),
    });
    renderPage('SUPPORT_AGENT');
    const user = userEvent.setup();
    await user.click(screen.getByRole('button', { name: /Analyze/ }));
    await user.type(screen.getByLabelText('Incident to analyse'), 'INC-78');
    await user.click(await screen.findByRole('option', { name: /INC-7846/ }));
    await user.click(screen.getByRole('button', { name: 'Analyse incident' }));
    expect(await screen.findByRole('article', { name: 'Incident summary' })).toHaveTextContent('Users cannot reach payroll.');
    const rootCause = await screen.findByRole('article', { name: 'Root-cause hypotheses' });
    expect(rootCause).toHaveTextContent('Connection pool exhaustion');
    expect(rootCause).toHaveTextContent('High likelihood');
  });

  it('Recommend shows the resolution suggestion with match, steps, runbook and articles', async () => {
    baseRoutes({
      'POST /ai/incidents/7846/resolution': json(
        aiResult({
          likelyCause: 'Database connection pool exhaustion',
          confidence: 87,
          steps: ['Check database pool utilization', 'Restart payroll application service'],
          runbook: { id: 11, title: 'Payroll service restart', requiresApproval: true },
          articles: [{ id: 1001, title: 'Payroll troubleshooting guide', averageRating: 4.8, ratingCount: 212 }],
        }),
      ),
    });
    renderPage();
    const user = userEvent.setup();
    await user.click(screen.getByRole('button', { name: /Recommend/ }));
    await user.type(screen.getByLabelText('Incident to resolve'), 'INC-78');
    await user.click(await screen.findByRole('option', { name: /INC-7846/ }));
    await user.click(screen.getByRole('button', { name: 'Recommend resolution' }));
    const card = await screen.findByRole('article', { name: 'SA AI Recommendation' });
    expect(within(card).getByText('87% Match')).toBeInTheDocument();
    expect(card).toHaveTextContent('Database connection pool exhaustion');
    expect(card).toHaveTextContent('Restart payroll application service');
    expect(within(card).getByRole('link', { name: 'Payroll service restart' })).toHaveAttribute('href', '/runbooks/11');
    expect(within(card).getByRole('link', { name: 'Payroll troubleshooting guide' })).toHaveAttribute('href', '/knowledge/1001');
    expect(within(card).getByText(/Requires Incident Manager approval/)).toBeInTheDocument();
  });

  it('Automate drafts a workflow and opens it in the builder with the suggestion in router state', async () => {
    baseRoutes({
      'GET /workflows/meta': json({ triggers: [], operators: [], fields: [{ field: 'priority', label: 'Priority', values: null }], actions: [] }),
      'POST /ai/workflow-suggestion': json(
        aiResult({
          name: 'Payroll incident – auto resolution',
          description: 'Starts the payroll runbook.',
          triggerEvent: 'INCIDENT_CREATED',
          definition: {
            conditions: { match: 'ALL', rules: [{ field: 'priority', operator: 'EQUALS', value: 'CRITICAL' }] },
            actions: [{ type: 'START_RUNBOOK', params: { runbookId: '11' } }],
            elseActions: [{ type: 'ASSIGN_DEPARTMENT', params: { departmentCode: 'IT-SD' } }],
          },
          explanation: 'Matches the goal.',
        }),
      ),
    });
    renderPage();
    const user = userEvent.setup();
    await user.click(screen.getByRole('button', { name: /Automate/ }));
    await user.type(screen.getByLabelText('What should be automated?'), 'Start the payroll runbook for critical payroll incidents');
    await user.click(screen.getByRole('button', { name: 'Draft workflow' }));
    const card = await screen.findByRole('article', { name: 'Payroll incident – auto resolution' });
    expect(card).toHaveTextContent('New Incident');
    expect(card).toHaveTextContent('Priority is CRITICAL');
    expect(card).toHaveTextContent('Trigger approved runbook');
    expect(card).toHaveTextContent('Assign to team');
    expect(within(card).getByText('Deterministic fallback — not AI-generated')).toBeInTheDocument();
    await user.click(within(card).getByRole('button', { name: 'Open in builder' }));
    await waitFor(() => expect(screen.getByText('Builder with Payroll incident – auto resolution (INCIDENT_CREATED)')).toBeInTheDocument());
  });
});
