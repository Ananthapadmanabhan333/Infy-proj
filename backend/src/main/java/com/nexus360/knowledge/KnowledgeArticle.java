package com.nexus360.knowledge;

import com.nexus360.cmdb.BusinessService;
import com.nexus360.common.BaseEntity;
import com.nexus360.incident.Category;
import com.nexus360.user.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import java.time.Instant;
import java.util.Arrays;
import java.util.List;
import lombok.Getter;
import lombok.Setter;

/** The {@code search_vector} column is generated by PostgreSQL and intentionally not mapped. */
@Getter
@Setter
@Entity
@Table(name = "knowledge_articles")
public class KnowledgeArticle extends BaseEntity {

    public enum ArticleType { GUIDE, SOLUTION, KNOWN_ERROR, FAQ }

    /** DRAFT → IN_REVIEW (submitted) → PUBLISHED → ARCHIVED. */
    public enum Status { DRAFT, IN_REVIEW, PUBLISHED, ARCHIVED }

    @Column(nullable = false, length = 20, unique = true, updatable = false)
    private String number;

    @Column(nullable = false, length = 200)
    private String title;

    @Column(nullable = false, length = 500)
    private String summary;

    @Column(nullable = false, columnDefinition = "text")
    private String content;

    @Enumerated(EnumType.STRING)
    @Column(name = "article_type", nullable = false, length = 20)
    private ArticleType articleType;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private Category category;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "service_id")
    private BusinessService service;

    @Column(length = 400)
    private String tags;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private Status status = Status.DRAFT;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "author_id")
    private User author;

    @Column(name = "view_count", nullable = false)
    private int viewCount;

    @Column(name = "helpful_count", nullable = false)
    private int helpfulCount;

    @Column(name = "not_helpful_count", nullable = false)
    private int notHelpfulCount;

    @Column(name = "read_minutes", nullable = false)
    private int readMinutes = 1;

    @Column(name = "rating_count", nullable = false)
    private int ratingCount;

    @Column(name = "rating_average", precision = 3, scale = 2)
    private java.math.BigDecimal ratingAverage;

    /** Release 1 helpful votes (no voter identity); the counters above add the derived Release 2 ratings to them. */
    @Column(name = "legacy_helpful_count", nullable = false)
    private int legacyHelpfulCount;

    @Column(name = "legacy_not_helpful_count", nullable = false)
    private int legacyNotHelpfulCount;

    @Column(name = "current_version", nullable = false)
    private int currentVersion = 1;

    @Column(name = "published_at")
    private Instant publishedAt;

    @Column(name = "is_demo", nullable = false)
    private boolean demo;

    @Version
    private long version;

    public List<String> tagList() {
        if (tags == null || tags.isBlank()) {
            return List.of();
        }
        return Arrays.stream(tags.split(",")).map(String::trim).filter(t -> !t.isEmpty()).toList();
    }
}
