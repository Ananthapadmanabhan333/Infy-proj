    /** Subject of incident features in "Recent Analyses". */
    private static String subject(Incident i) {
        String s = i.getNumber() + " · " + i.getTitle();
        return s.length() > 200 ? s.substring(0, 199) + "…" : s;
    }

    public List<InteractionDto> recentInteractions(Actor actor, Integer size) {
        int n = size == null ? 5 : Math.max(1, Math.min(size, 50));
        return interactions.findByUserIdAndSuccessTrueOrderByCreatedAtDescIdDesc(actor.id(), org.springframework.data.domain.PageRequest.of(0, n))
                .stream().map(a -> new InteractionDto(a.getId(), a.getFeature(), a.getSubject(), Source.valueOf(a.getSource()), a.getCreatedAt()))
                .toList();
    }

    public AiStatus status() {
        String lastError = interactions.findFirstBySourceAndSuccessFalseOrderByCreatedAtDesc(Source.LLM.name())
                .map(AiInteraction::getError).orElse(null);
        return new AiStatus(llm.name(), llm.model(), llm.configured(), llmEnabled(), true, lastError);
    }

