    public AiResult<ClassificationSuggestion> classify(Long incidentId, Actor actor) {
        Incident i = incidentQueries.load(incidentId, actor);
        List<BusinessService> catalogue = services.findAllByOrderByTierAscNameAsc();
        return run("classify", incidentId, subject(i), actor, () -> {
            String serviceList = catalogue.stream().map(s -> s.getCode() + " = " + s.getName() + " (tier " + s.getTier() + ")")
                    .collect(Collectors.joining("\n"));
            LlmSchemas.Classification out = llm.generate(SYSTEM_BASE + " Classify IT incidents for routing.",
                    "Business services:\n" + serviceList + "\n\n" + incidentBlock(i)
                            + "\n\nChoose the category, the affected service code (or NONE), the business impact and the urgency.",
                    LlmSchemas.Classification.class);
            Category category = parseEnum(Category.class, out.category, "category");
            Level impact = parseEnum(Level.class, out.impact, "impact");
            Level urgency = parseEnum(Level.class, out.urgency, "urgency");
            BusinessService service = out.serviceCode == null || "NONE".equalsIgnoreCase(out.serviceCode) ? null
                    : catalogue.stream().filter(s -> s.getCode().equalsIgnoreCase(out.serviceCode.trim())).findFirst()
                    .orElseThrow(() -> new LlmException(LlmException.Reason.INVALID_OUTPUT, "Unknown service code " + out.serviceCode));
            return new ClassificationSuggestion(category, service == null ? null : service.getId(), service == null ? null : service.getName(),
                    impact, urgency, PriorityCalculator.calculate(impact, urgency), clamp(out.confidence), nonBlank(out.rationale));
        }, () -> fallback.classify(i));
    }

    public AiResult<IncidentSummaryAi> summarize(Long incidentId, Actor actor) {
        Incident i = incidentQueries.load(incidentId, actor);
        SlaSnapshot snapshot = slas.findByIncidentId(incidentId).map(s -> mapper.snapshot(s, clock.instant())).orElse(null);
        var commentList = comments.findByIncidentIdOrderByCreatedAtAscIdAsc(incidentId);
        int children = (int) incidents.countByParentId(incidentId);
        return run("summarize", incidentId, subject(i), actor, () -> {
            String timeline = incidentQueries.history(incidentId, actor).stream().limit(40)
                    .map(h -> h.createdAt() + " " + h.eventType() + " " + Objects.toString(h.field(), "") + " "
                            + Objects.toString(h.newValue(), "") + " " + Objects.toString(h.message(), ""))
                    .collect(Collectors.joining("\n"));
            String notes = commentList.stream().limit(20).map(c -> (c.isInternal() ? "[work note] " : "[comment] ") + c.getBody())
                    .collect(Collectors.joining("\n"));
            LlmSchemas.Summary out = llm.generate(SYSTEM_BASE + " Write concise incident summaries for operations managers.",
                    incidentBlock(i) + "\n<data>\nSLA: " + (snapshot == null ? "none" : snapshot) + "\nLinked duplicate reports: " + children
                            + "\nTimeline:\n" + timeline + "\nComments:\n" + notes + "\n</data>", LlmSchemas.Summary.class);
            return new IncidentSummaryAi(nonBlank(out.summary), safeList(out.keyFacts), safeList(out.nextSteps));
        }, () -> fallback.summarize(i, snapshot, children, commentList.size()));
    }

    public AiResult<DuplicateSuggestions> duplicates(Long incidentId, Actor actor) {
        Incident i = incidentQueries.load(incidentId, actor);
        List<DuplicateCandidate> candidates = incidentQueries.duplicatesFor(incidentId, actor);
        String ruleExplanation = "Ranked by token and trigram similarity of title and description, boosted for the same service and category.";
        if (candidates.isEmpty()) {
            return fallbackResult("duplicates", incidentId, subject(i), actor, new DuplicateSuggestions(List.of(),
                    "No unresolved incident in the detection window is similar enough. " + ruleExplanation), "No candidates to rank");
        }
        return run("duplicates", incidentId, subject(i), actor, () -> {
            String list = candidates.stream().map(c -> c.number() + ": " + c.title() + " [" + c.status() + ", " + c.serviceName() + "]")
                    .collect(Collectors.joining("\n"));
            LlmSchemas.Ranking out = llm.generate(SYSTEM_BASE + " Decide which candidate incidents describe the same underlying problem.",
                    incidentBlock(i) + "\n<candidates>\n" + list + "\n</candidates>\nReturn only true duplicates.", LlmSchemas.Ranking.class);
            Map<String, DuplicateCandidate> byNumber = candidates.stream().collect(Collectors.toMap(DuplicateCandidate::number, Function.identity()));
            List<DuplicateCandidate> ranked = safeItems(out.items).stream().filter(r -> byNumber.containsKey(r.reference))
                    .map(r -> byNumber.get(r.reference)).distinct().toList();
            return new DuplicateSuggestions(ranked, nonBlank(out.explanation));
        }, () -> new DuplicateSuggestions(candidates, ruleExplanation));
    }

    public AiResult<KnowledgeRecommendations> knowledge(Long incidentId, Actor actor) {
        Incident i = incidentQueries.load(incidentId, actor);
        List<ArticleSummary> candidates = knowledge.recommend(i.getTitle() + " " + Objects.toString(i.getDescription(), ""),
                i.getService() == null ? null : i.getService().getId(), 8);
        String ruleExplanation = "Ranked by PostgreSQL full-text relevance against the incident text, boosted for the same service.";
        if (candidates.isEmpty()) {
            return fallbackResult("knowledge", incidentId, subject(i), actor, new KnowledgeRecommendations(List.of(),
                    "No published article matches this incident. " + ruleExplanation), "No candidates to rank");
        }
        return run("knowledge", incidentId, subject(i), actor, () -> {
            String list = candidates.stream().map(a -> a.number() + ": " + a.title() + " — " + a.summary()).collect(Collectors.joining("\n"));
            LlmSchemas.Ranking out = llm.generate(SYSTEM_BASE + " Recommend knowledge articles that help resolve an incident.",
                    incidentBlock(i) + "\n<candidates>\n" + list + "\n</candidates>\nReturn only articles that would genuinely help.",
                    LlmSchemas.Ranking.class);
            Map<String, ArticleSummary> byNumber = candidates.stream().collect(Collectors.toMap(ArticleSummary::number, Function.identity()));
            List<ArticleSummary> ranked = safeItems(out.items).stream().filter(r -> byNumber.containsKey(r.reference))
                    .map(r -> byNumber.get(r.reference)).distinct().limit(5).toList();
            return new KnowledgeRecommendations(ranked, nonBlank(out.explanation));
        }, () -> new KnowledgeRecommendations(candidates.stream().limit(5).toList(), ruleExplanation));
    }

    public AiResult<RootCauseAnalysis> rootCause(Long incidentId, Actor actor) {
        Incident i = incidentQueries.load(incidentId, actor);
        int children = (int) incidents.countByParentId(incidentId);
        return run("root_cause", incidentId, subject(i), actor, () -> {
            String related = i.getService() == null ? "none" : incidents.findTop10ByServiceIdOrderByCreatedAtDesc(i.getService().getId()).stream()
                    .filter(x -> !x.getId().equals(i.getId()))
                    .map(x -> x.getNumber() + " " + x.getTitle() + " [" + x.getStatus() + "]" + (x.getRootCause() == null ? "" : " root cause: " + x.getRootCause()))
                    .collect(Collectors.joining("\n"));
            LlmSchemas.RootCause out = llm.generate(SYSTEM_BASE + " Suggest probable root causes and diagnostic checks for IT incidents.",
                    incidentBlock(i) + "\n<data>\nLinked duplicate reports: " + children + "\nRecent incidents on the same service:\n" + related + "\n</data>",
                    LlmSchemas.RootCause.class);
            List<Hypothesis> hypotheses = new ArrayList<>();
            for (LlmSchemas.Hypothesis h : out.hypotheses == null ? List.<LlmSchemas.Hypothesis>of() : out.hypotheses) {
                String likelihood = h.likelihood == null ? "MEDIUM" : h.likelihood.trim().toUpperCase(Locale.ROOT);
                hypotheses.add(new Hypothesis(nonBlank(h.cause), List.of("HIGH", "MEDIUM", "LOW").contains(likelihood) ? likelihood : "MEDIUM",
                        safeList(h.evidence), safeList(h.suggestedChecks)));
            }
            if (hypotheses.isEmpty()) {
                throw new LlmException(LlmException.Reason.INVALID_OUTPUT, "No hypotheses returned");
            }
            return new RootCauseAnalysis(hypotheses.stream().limit(4).toList());
        }, () -> fallback.rootCause(i, children));
    }

    /**
     * Resolution advice for an incident: likely cause, confidence, steps, the best-fitting runbook and articles. The LLM
     * may only choose among the retrieved runbooks and articles; the deterministic engine derives every value from them.
     */
    public AiResult<ResolutionSuggestion> resolution(Long incidentId, Actor actor) {
        Incident i = incidentQueries.load(incidentId, actor);
        ResolutionAdvisor.Evidence evidence = resolutionAdvisor.gather(i);
        return run("resolution", incidentId, subject(i), actor, () -> {
            String similar = evidence.incidents().stream().map(s -> s.incident().getNumber() + " (similarity " + Math.round(s.similarity() * 100)
                            + "%): " + s.incident().getTitle() + " | root cause: " + Objects.toString(s.incident().getRootCause(), "not recorded")
                            + " | resolution: " + Objects.toString(s.incident().getResolutionNotes(), ""))
                    .collect(Collectors.joining("\n"));
            String kb = evidence.articles().stream().map(a -> a.number() + ": " + a.title() + " — " + a.summary()).collect(Collectors.joining("\n"));
            String rb = evidence.runbooks().stream().map(r -> "RB-" + r.runbook().getId() + ": " + r.runbook().getTitle()
                    + (r.runbook().isRequiresApproval() ? " (approval required)" : "")).collect(Collectors.joining("\n"));
            LlmSchemas.Resolution out = llm.generate(SYSTEM_BASE + " Recommend how to resolve an IT incident using similar resolved incidents, "
                            + "knowledge articles and runbooks. Choose runbooks and articles only from the candidates.",
                    incidentBlock(i) + "\n<candidates>\nSimilar resolved incidents:\n" + (similar.isEmpty() ? "none" : similar)
                            + "\nArticles:\n" + (kb.isEmpty() ? "none" : kb) + "\nRunbooks:\n" + (rb.isEmpty() ? "none" : rb) + "\n</candidates>",
                    LlmSchemas.Resolution.class);
            RunbookRef runbook = null;
            if (out.runbookReference != null && !"NONE".equalsIgnoreCase(out.runbookReference.trim())) {
                String ref = out.runbookReference.trim();
                runbook = evidence.runbooks().stream().filter(r -> ("RB-" + r.runbook().getId()).equalsIgnoreCase(ref))
                        .map(r -> ResolutionAdvisor.ref(r.runbook())).findFirst()
                        .orElseThrow(() -> new LlmException(LlmException.Reason.INVALID_OUTPUT, "Unknown runbook reference " + ref));
            }
            Map<String, ArticleSummary> byNumber = evidence.articles().stream().collect(Collectors.toMap(ArticleSummary::number, Function.identity()));
            List<ArticleSummary> chosen = (out.articleReferences == null ? List.<String>of() : out.articleReferences).stream()
                    .filter(Objects::nonNull).map(String::trim).filter(byNumber::containsKey).distinct().map(byNumber::get).limit(3).toList();
            if (out.confidence < 0 || out.confidence > 100) {
                throw new LlmException(LlmException.Reason.INVALID_OUTPUT, "Confidence out of range");
            }
            List<String> steps = safeList(out.steps);
            if (steps.isEmpty()) {
                throw new LlmException(LlmException.Reason.INVALID_OUTPUT, "No resolution steps returned");
            }
            ResolutionSuggestion base = resolutionAdvisor.suggest(i, evidence);
            return new ResolutionSuggestion(nonBlank(out.likelyCause), out.confidence, steps, runbook, chosen, base.matchedIncidents(),
                    "LLM analysis of " + evidence.incidents().size() + " similar resolved incident(s), " + evidence.articles().size()
                            + " article(s) and " + evidence.runbooks().size() + " runbook(s).");
        }, () -> resolutionAdvisor.suggest(i, evidence));
    }

    /** Proposes a workflow for a plain-language goal. The proposal is validated against the workflow model and never saved. */
    public AiResult<WorkflowSuggestion> workflowSuggestion(String goal, Actor actor) {
        String g = goal.trim();
        String subject = g.length() > 200 ? g.substring(0, 199) + "…" : g;
        return run("workflow_suggestion", null, subject, actor, () -> {
            var meta = workflowSuggester.meta();
            LlmSchemas.WorkflowSuggestion out = llm.generate(SYSTEM_BASE + " Design IT service-management automation workflows. Use only the "
                            + "triggers, condition fields, operators, action types and parameters listed in <data>.",
                    "<data>\n" + meta + "\n</data>\n\nGoal: " + g, LlmSchemas.WorkflowSuggestion.class);
            return workflowSuggester.validate(workflowSuggester.fromLlm(out));
        }, () -> workflowSuggester.deterministic(g));
    }

