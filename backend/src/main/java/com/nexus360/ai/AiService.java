    /** Insights are organisation-wide, so page views share one result instead of each triggering a model call. */
    private static final Duration INSIGHTS_TTL = Duration.ofMinutes(10);

    private record CachedInsights(AiResult<OperationalInsights> result, Instant generatedAt) {}

    private volatile CachedInsights cachedInsights;

    public AiResult<OperationalInsights> insights(Actor actor) {
        return insights(actor, false);
    }

    /** Returns the shared result while it is fresh; {@code refresh} regenerates it (explicit user request). */
    public AiResult<OperationalInsights> insights(Actor actor, boolean refresh) {
        CachedInsights cached = cachedInsights;
        if (!refresh && cached != null && cached.generatedAt().isAfter(clock.instant().minus(INSIGHTS_TTL))) {
            return cached.result();
        }
        AiResult<OperationalInsights> result = generateInsights(actor);
        cachedInsights = new CachedInsights(result, clock.instant());
        return result;
    }

    private AiResult<OperationalInsights> generateInsights(Actor actor) {
        return run("insights", null, "Operational insights", actor, () -> {
            LlmSchemas.Insights out = llm.generate(SYSTEM_BASE + " Identify operational trends and risks for an IT operations manager.",
                    "<data>\n" + metricsSnapshot() + "\n</data>", LlmSchemas.Insights.class);
            List<Insight> list = new ArrayList<>();
            for (LlmSchemas.Insight x : out.insights == null ? List.<LlmSchemas.Insight>of() : out.insights) {
                Severity severity;
                try {
                    severity = Severity.valueOf(Objects.toString(x.severity, "INFO").trim().toUpperCase(Locale.ROOT));
                } catch (IllegalArgumentException e) {
                    severity = Severity.INFO;
                }
                String confidence = Objects.toString(x.confidence, "MEDIUM").trim().toUpperCase(Locale.ROOT);
                list.add(new Insight(nonBlank(x.title), nonBlank(x.detail), severity, x.metric == null || x.metric.isBlank() ? null : x.metric,
                        List.of("HIGH", "MEDIUM", "LOW").contains(confidence) ? confidence : "MEDIUM"));
            }
            if (list.isEmpty()) {
                throw new LlmException(LlmException.Reason.INVALID_OUTPUT, "No insights returned");
            }
            return new OperationalInsights(list.stream().limit(5).toList(), analytics.hourlyCreated(30));
        }, fallback::insights);
    }

    public AiResult<AskResponse> ask(String question, Actor actor) {
        String q = question.trim();
        return run("ask", null, q.length() > 200 ? q.substring(0, 199) + "…" : q, actor, () -> {
            LlmSchemas.Answer out = llm.generate(SYSTEM_BASE + " Answer reporting questions about IT operations using only the metrics provided.",
                    "<data>\n" + metricsSnapshot() + "\n</data>\n\nQuestion: " + q, LlmSchemas.Answer.class);
            List<DataPoint> data = (out.data == null ? List.<LlmSchemas.DataPoint>of() : out.data).stream()
                    .filter(d -> d.label != null && Double.isFinite(d.value)).limit(12)
                    .map(d -> new DataPoint(d.label, d.value)).toList();
            return new AskResponse(nonBlank(out.answer), data, nonBlank(out.basis) + " (metrics snapshot generated " + clock.instant() + ")");
        }, () -> fallback.ask(q));
    }

